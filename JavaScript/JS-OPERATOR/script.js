// Aritmatic Operator
let x = 5;
let y = 11;

let tambah = x + y;
let kurang = x - y;
let bagi = x / y;
let kali = x * y;
let modulus = y % x;

console.log(tambah, kurang, bagi, kali, modulus);

// Condisional Operator
let s = 20;
//!= dibaca tidak sama dengan
if(s != 20){
    console.log('Kondisi Benar');
}else{
    console.log('Kondisi Salah');
}


//== dibaca sama dengan
if(s == 20){
    console.log('Kondisi Benar');
}else{
    console.log('Kondisi Salah');
}